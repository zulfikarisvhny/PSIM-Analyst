// lib/scouting/matchStats.ts
// Per-team round-by-round detailed stats, keyed by full team name. Generated
// directly from CSV exports (not hand-transcribed):
//  - Bhayangkara: 5 separate "Bhayangkara *.csv" files in ~/Documents/PSIM
//    (Possession, Shooting, Duel and Defensive, Distribution, Dicipline).
//  - Persita: one combined "Persita all team stats.csv" — already merges
//    every category into one file per round, plus extra goalkeeping columns
//    (Saves, Sweeper Actions, High Claims, Crosses Not Claimed) that the
//    Bhayangkara export doesn't have, hence the optional `goalkeeping` field.
// Regenerate from source CSVs rather than hand-editing if they update.
//
// Bhayangkara round 30 (vs Persib) and Persita round 7 (vs Persib) both have
// a known result but an unresolved "? - ?" score in the source — homeScore/
// awayScore are null for those rounds.

export interface MatchStatsEntry {
  round: number;
  date: string;
  opponentShort: string;
  venue: "H" | "A";
  result: "W" | "D" | "L";
  homeScore: number | null;
  awayScore: number | null;
  avgRating: number;
  possession: { touches: number; unsuccessfulTouches: number; possessionLost: number };
  shooting: {
    shots: number; shotsOnTarget: number; shotsOffTarget: number; shotsBlocked: number;
    goals: number; hitWoodwork: number; bigChancesMissed: number; xg: number;
  };
  duelDefensive: {
    aerialDuelsLost: number; aerialDuelsWon: number; duelsLost: number; duelsWon: number;
    challengesLost: number; contests: number; contestsWon: number; clearances: number;
    blockedShots: number; interceptions: number; ballRecoveries: number; tackles: number;
    tacklesWon: number; errorsToShot: number; dispossessed: number;
  };
  distribution: {
    passes: number; accPasses: number; longBalls: number; accLongBalls: number;
    assists: number; ownHalfPasses: number; accOwnHalfPasses: number; oppHalfPasses: number;
    accOppHalfPasses: number; crosses: number; accCrosses: number; keyPasses: number;
  };
  discipline: {
    foulsDrawn: number; foulsCommitted: number; offsides: number;
    penConceded: number; penWon: number; ownGoals: number;
  };
  /** Only present for teams whose source export included keeper stats (currently Persita). */
  goalkeeping?: {
    crossesNotClaimed: number; highClaims: number; savesBox: number;
    saves: number; sweeperActions: number; accSweeperActions: number;
  };
}

